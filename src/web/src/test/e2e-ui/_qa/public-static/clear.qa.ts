test("real Alice logout and Bob login retain server facts while device Clear removes all represented payloads", async ({ caseActors, caseResources }, testInfo) => {
  const actors = await caseActors(["alice", "bob"])
  const aliceServer = await actors.seed.seedServer("alice", `clear-alice-${Date.now()}`)
  const aliceChannel = await actors.seed.seedChannel("alice", aliceServer, "alice-private")
  const aliceText = `Alice private native clear ${Date.now()}`
  const aliceMessage = await actors.seed.seedMessage("alice", aliceChannel, aliceText)
  const bobServer = await actors.seed.seedServer("bob", `clear-bob-${Date.now()}`)
  const bobChannel = await actors.seed.seedChannel("bob", bobServer, "bob-private")
  const bobText = `Bob native clear ${Date.now()}`
  const bobMessage = await actors.seed.seedMessage("bob", bobChannel, bobText)
  const context = await caseResources.newContext()
  const page = await context.newPage()
  await actors.signInOnPage("alice", page)
  await gotoAfterUserWsAuth(page, `/c/channels/${aliceServer}/${aliceChannel}`)
  await expect(page.getByText(aliceText, { exact: true }).first()).toBeVisible()
  const aliceKey = `alook:qc:cache:${actors.userId("alice")}:client`
  await expect.poll(async () => (await deviceSnapshot(page)).payloadKeys).toContain(aliceKey)
  const captured = await deviceSnapshot(page)
  const aliceUiCookie = (await context.cookies()).filter(cookie => cookie.name.startsWith("better-auth")).map(cookie => `${cookie.name}=${cookie.value}`).join("; ")
  expect(Boolean(aliceUiCookie)).toBe(true)
  expect(aliceUiCookie === actors.sessionCookie("alice")).toBe(false)
  await page.getByTestId(tid.userSettingsOpen).click()
  await page.getByRole("button", { name: "Log out", exact: true }).click()
  await page.waitForURL(/\/sign-in/, { waitUntil: "commit" })
  await expect.poll(async () => (await context.cookies()).some(cookie => cookie.name.startsWith("better-auth"))).toBe(false)
  const retired = await fetch(`${WEB_URL}/api/ws/token?refresh=1`, { signal: qaDeadlineSignal(caseResources), headers: { Cookie: aliceUiCookie, Origin: WEB_URL } })
  expect(retired.status).toBe(401)
  expect(retired.headers.get("content-type")).toBe("text/plain;charset=UTF-8")
  expect(await retired.text()).toBe("Unauthorized")
  expect((await qaApi<{ userId: string }>(actors, caseResources, "alice", "/api/ws/token?refresh=1")).body.userId).toBe(actors.userId("alice"))
  const afterLogout = await deviceSnapshot(page)
  expect(afterLogout.payloadKeys).not.toContain(aliceKey)
  expect(afterLogout.epoch).toBe(captured.epoch)
  await actors.signInOnPage("bob", page)
  const proxy = await proxyCommunityWebSockets(context)
  await gotoAfterUserWsAuth(page, `/c/channels/${bobServer}/${bobChannel}`)
  await expect(page.getByText(bobText, { exact: true }).first()).toBeVisible()
  await expect(page.getByText(aliceText, { exact: true })).toHaveCount(0)
  const bobKey = `alook:qc:cache:${actors.userId("bob")}:client`
  await expect.poll(async () => (await deviceSnapshot(page)).payloadKeys).toContain(bobKey)
  const blog = await context.newPage()
  await blog.goto("/blog")
  await rootWorker(blog)
  const code = actualRuntimeAsset("Nplus1", "code")
  await warmBoundAsset(blog, code)
  await warmBoundAsset(blog, actualRuntimeAsset("Nplus1", "images"))
  const oldNamespaces = await seedOldPublicNamespace(blog, code.url)
  await blog.close()
  const sentinel = await prepareUnrelatedNativeState(page, testInfo.testId)
  const residual = await insertArtificialRetiredResidual(page, actors.userId("alice"), captured)
  const before = await deviceSnapshot(page)
  expect(before.payloadKeys).toEqual(expect.arrayContaining([...residual.keys, bobKey]))
  const bobMessagesBefore = await qaApi<{ messages: Array<{ id: string; seq: number; content: string }> }>(actors, caseResources, "bob", `/api/community/channels/${bobChannel}/messages`)
  const original = bobMessagesBefore.body.messages.find(message => message.id === bobMessage)!
  expect(original).toBeTruthy()
  const observer = await observeDeviceClear(page, caseResources, before.epoch)
  const ui = await clearThroughSettings(page)
  const committed = await observer.result()
  expect(committed.epoch).not.toBe(before.epoch)
  expect(committed.payloadKeys).toEqual([])
  expect(preservedDeviceMetadata(committed)).toEqual(preservedDeviceMetadata(before))
  await observer.close()
  const nativeAfter = await publicNativeSnapshot(page)
  expect(Object.keys(nativeAfter.caches).filter(name => name.startsWith("alook-public-"))).toEqual([])
  expect(nativeAfter.expiration.filter(row => row.cacheName.startsWith("alook-public-"))).toEqual([])
  await expectUnrelatedNativeState(page, sentinel)
  const identity = await context.request.get("/api/ws/token?refresh=1")
  expect(identity.status()).toBe(200)
  expect((await identity.json()).userId).toBe(actors.userId("bob"))
  const denied = await context.request.get(`/api/community/channels/${aliceChannel}/messages`)
  expect([403, 404]).toContain(denied.status())
  const retained = (await qaApi<{ messages: typeof bobMessagesBefore.body.messages }>(actors, caseResources, "bob", `/api/community/channels/${bobChannel}/messages`)).body.messages.find(message => message.id === bobMessage)
  expect(retained).toEqual(original)
  expect((await qaApi<{ messages: Array<{ id: string }> }>(actors, caseResources, "alice", `/api/community/channels/${aliceChannel}/messages`)).body.messages.some(message => message.id === aliceMessage)).toBe(true)
  const frameStart = proxy.frames.length
  const post = await qaApi<{ message: { id: string; seq: number } }>(actors, caseResources, "bob", `/api/community/channels/${bobChannel}/messages`, { method: "POST", body: JSON.stringify({ content: "Bob post-clear real message" }) })
  expect(post.status).toBe(201)
  expect(post.body.message.seq).toBeGreaterThan(original.seq)
  await expect.poll(() => proxy.frames.slice(frameStart).flatMap(communityFrameEvents).some(event => event.type === "community:message.create" && (event.message?.id === post.body.message.id || event.messageId === post.body.message.id))).toBe(true)
  await expect(page.getByText(aliceText, { exact: true })).toHaveCount(0)
  await attachQa(testInfo, "device-clear-natural-login-and-artificial-residual", { ui, sameDeviceContextCount: 1, naturalLogoutPayloadAbsent: !afterLogout.payloadKeys.includes(aliceKey), oldNamespaces, residual, beforeEpoch: before.epoch, committed, uiCompletedPayloadKeys: (await deviceSnapshot(page)).payloadKeys, original, retained, newMessage: post.body.message, permissionStatus: denied.status(), nativeAfter, limitation: "Native metadata preservation and cross-account visibility are covered; no new stale-persister API is injected into the product" })
})

test("real settings Clear reports an already-held image writer separately from later public repopulation", async ({ caseActors, caseResources }, testInfo) => {
  const actors = await caseActors(["bob"])
  const business = await ownedBusiness(actors, "bob", caseResources)
  const original = await business.write("pending writer original message")
  const imagePage = await business.context.newPage()
  await imagePage.goto("/blog")
  await rootWorker(imagePage)
  await warmBoundAsset(imagePage, actualRuntimeAsset("Nplus1", "code"))
  const sentinel = await prepareUnrelatedNativeState(business.page, testInfo.testId)
  const snapshot = await publicNativeSnapshot(imagePage, [runtimeName("images")])
  const existing = new Set(snapshot.caches[runtimeName("images")]?.map(entry => new URL(entry.url).pathname))
  const image = releaseAssets("Nplus1").find(asset => asset.kind === "images" && !existing.has(asset.url)) ?? actualRuntimeAsset("Nplus1", "images")
  const worker = business.context.serviceWorkers().find(worker => worker.url() === new URL("/sw.js", imagePage.url()).href)
  expect(worker).toBeTruthy()
  const fault = await ownSwFault(caseResources, business.context, new URL(image.url, imagePage.url()).href, Promise.resolve(worker!), "hold")
  const operation = caseResources.own({ pending: undefined as Promise<Awaited<ReturnType<typeof readNativeResource>>> | undefined, accepted: false }, async state => {
    if (!state.accepted) await fault.close()
    if (state.pending) await state.pending.catch(error => { if (state.accepted) throw error })
  })
  operation.value.pending = readNativeResource(imagePage, image.url)
  void operation.value.pending.catch(() => {})
  await expect.poll(() => fault.held()).toBe(true)
  const before = { device: await deviceSnapshot(business.page), public: await publicNativeSnapshot(imagePage) }
  const observer = await observeDeviceClear(business.page, caseResources, before.device.epoch)
  const ui = await clearThroughSettings(business.page)
  const committed = await observer.result()
  expect(committed.epoch).not.toBe(before.device.epoch)
  expect(committed.payloadKeys).toEqual([])
  expect(preservedDeviceMetadata(committed)).toEqual(preservedDeviceMetadata(before.device))
  await observer.close()
  const afterUi = await publicNativeSnapshot(imagePage)
  expect(Object.keys(afterUi.caches).filter(name => name.startsWith("alook-public-"))).toEqual([])
  expect(afterUi.expiration.filter(row => row.cacheName.startsWith("alook-public-"))).toEqual([])
  fault.release()
  const resource = await withinQaDeadline(operation.value.pending, caseResources.deadline)
  expect(resource).toMatchObject({ bytes: image.bytes, sha256: image.sha256, fromServiceWorker: true })
  operation.value.accepted = true
  await operation.close()
  await expect.poll(() => fault.records.every(record => record.completed)).toBe(true)
  await fault.close()
  const afterRelease = await publicNativeSnapshot(imagePage)
  await expectUnrelatedNativeState(business.page, sentinel)
  expect(await business.read(original.id)).toMatchObject({ id: original.id, seq: original.seq, content: original.content })
  const next = await business.write("pending writer post-clear message")
  expect(next.seq).toBeGreaterThan(original.seq)
  await attachQa(testInfo, "clear-with-real-in-flight-writer", { ui, before, committed, afterUi, afterRelease, heldRequest: fault.records, resource, original, next, classification: "Any matching entry after release belongs to the pre-clear held request; permanent public-cache emptiness is not asserted" })
})
