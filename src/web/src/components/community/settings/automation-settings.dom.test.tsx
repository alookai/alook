import React from "react"
import { describe, it, expect, vi, beforeEach } from "vitest"
import { render, screen, setupUser, waitFor } from "@/test/react-dom-harness"
import type { AutomationAccessCode } from "@alook/shared"
import { AutomationCodeForm, AutomationSettings } from "./automation-settings"

vi.mock("./automation-setup-prompt", () => ({ AutomationSetupPrompt: () => null }))

const fixture: AutomationAccessCode = { id: "code-1", name: "Build script", createdAt: "2026-01-01T00:00:00Z", expiresAt: "2030-01-01T00:00:00Z", permissions: [{ permission: "bot.create", limit: 12, period: "day" }] }
const state = vi.hoisted(() => ({ execute: vi.fn(), refetch: vi.fn(), data: { accessCodes: [] as AutomationAccessCode[] }, isError: false, isPending: false }))
vi.mock("@/hooks/community/use-automation", () => ({ useAutomation: () => ({ list: { data: state.data, isError: state.isError, isPending: state.isPending, refetch: state.refetch }, execute: state.execute, pending: false }) }))
vi.mock("@/hooks/community/use-community-view-source", () => ({ useCommunityViewSource: () => ({ capture: () => Object.assign(() => {}, { signal: new AbortController().signal }) }) }))
beforeEach(() => {
  state.execute.mockReset(); state.refetch.mockReset(); state.data = { accessCodes: [] }; state.isError = false; state.isPending = false
})

describe("Automation form", () => {
  it("requires a permission and creates with 24h and independent default rates", async () => {
    const user = setupUser(), save = vi.fn().mockResolvedValue(undefined)
    render(<AutomationCodeForm pending={false} onCancel={() => {}} onSave={save} />)
    await user.type(screen.getByRole("textbox", { name: "Name" }), "Deploy")
    for (const name of ["List machines", "List friends", "List servers"]) await user.click(screen.getByRole("checkbox", { name }))
    await user.click(screen.getByRole("button", { name: "Create access code" }))
    expect(save).not.toHaveBeenCalled()
    expect(screen.getByRole("alert")).toHaveTextContent("at least one permission")
    await user.click(screen.getByRole("checkbox", { name: "Create bots" }))
    await user.click(screen.getByRole("checkbox", { name: "Create servers" }))
    await user.click(screen.getByRole("button", { name: "Advanced" }))
    await user.clear(screen.getByRole("spinbutton", { name: "Create bots request limit" }))
    await user.type(screen.getByRole("spinbutton", { name: "Create bots request limit" }), "5")
    await user.click(screen.getByRole("button", { name: "Create access code" }))
    expect(save).toHaveBeenCalledWith({ name: "Deploy", expiresIn: "24h", permissions: [{ permission: "bot.create", limit: 5, period: "hour" }, { permission: "server.create", limit: 64, period: "hour" }] }, true)
  })
  it("groups six permissions and defaults only the three reads on", async () => {
    const user = setupUser(), save = vi.fn().mockResolvedValue(undefined)
    render(<AutomationCodeForm pending={false} onCancel={() => {}} onSave={save} />)
    expect(screen.getByRole("group", { name: /^Read$/ })).toBeInTheDocument()
    expect(screen.getByRole("group", { name: /^Write$/ })).toBeInTheDocument()
    expect(screen.getAllByRole("checkbox")).toHaveLength(6)
    for (const name of ["List machines", "List friends", "List servers"]) expect(screen.getByRole("checkbox", { name })).toBeChecked()
    for (const name of ["Create bots", "Create servers", "Invite friends to servers"]) expect(screen.getByRole("checkbox", { name })).not.toBeChecked()
    await user.type(screen.getByRole("textbox", { name: "Name" }), "Invitations")
    await user.click(screen.getByRole("checkbox", { name: "Invite friends to servers" }))
    await user.click(screen.getByRole("button", { name: "Create access code" }))
    expect(save).toHaveBeenCalledWith({ name: "Invitations", expiresIn: "24h", permissions: ["server.invite", "machine.read", "friend.read", "server.read"].map((permission) => ({ permission, limit: 64, period: "hour" })) }, true)
  })
  it("hides rates in Advanced without losing an edited limit when collapsed", async () => {
    const user = setupUser(), save = vi.fn().mockResolvedValue(undefined)
    render(<AutomationCodeForm code={fixture} pending={false} onCancel={() => {}} onSave={save} />)
    expect(screen.queryByRole("spinbutton")).not.toBeInTheDocument()
    expect(screen.getByRole("button", { name: "Advanced" })).toHaveAttribute("aria-expanded", "false")
    await user.click(screen.getByRole("button", { name: "Advanced" }))
    await user.clear(screen.getByRole("spinbutton"))
    await user.type(screen.getByRole("spinbutton"), "20")
    await user.click(screen.getByRole("button", { name: "Advanced" }))
    expect(screen.queryByRole("spinbutton")).not.toBeInTheDocument()
    await user.click(screen.getByRole("button", { name: "Save changes" }))
    expect(save).toHaveBeenCalledWith(expect.objectContaining({ permissions: [{ permission: "bot.create", limit: 20, period: "day" }] }), false)
  })
  it("opens Advanced to reveal invalid limits submitted after collapsing", async () => {
    const user = setupUser(), save = vi.fn()
    render(<AutomationCodeForm code={fixture} pending={false} onCancel={() => {}} onSave={save} />)
    await user.click(screen.getByRole("button", { name: "Advanced" }))
    await user.clear(screen.getByRole("spinbutton"))
    await user.type(screen.getByRole("spinbutton"), "0")
    await user.click(screen.getByRole("button", { name: "Advanced" }))
    await user.click(screen.getByRole("button", { name: "Save changes" }))
    expect(save).not.toHaveBeenCalled()
    expect(screen.getByRole("spinbutton")).toHaveValue(0)
    expect(screen.getByRole("alert")).toHaveTextContent("whole-number limit")
  })
  it("prepopulates edits and preserves expiration unless a preset is selected", async () => {
    const user = setupUser(), save = vi.fn().mockResolvedValue(undefined)
    render(<AutomationCodeForm code={fixture} pending={false} onCancel={() => {}} onSave={save} />)
    await user.click(screen.getByRole("button", { name: "Advanced" }))
    expect(screen.getByRole("spinbutton")).toHaveValue(12)
    expect(screen.getByRole("combobox", { name: "Expiration" })).toHaveTextContent("Keep current expiration")
    await user.click(screen.getByRole("button", { name: "Save changes" }))
    expect(save).toHaveBeenLastCalledWith(expect.objectContaining({ permissions: fixture.permissions }), false)
    await user.click(screen.getByRole("combobox", { name: "Expiration" }))
    await user.click(await screen.findByRole("option", { name: "7 days" }))
    await user.click(screen.getByRole("button", { name: "Save changes" }))
    expect(save).toHaveBeenLastCalledWith(expect.objectContaining({ expiresIn: "7d" }), true)
  })
  it("omits a removed permission and preserves draft when save fails", async () => {
    const user = setupUser(), save = vi.fn().mockRejectedValue(new Error("Try again later"))
    render(<AutomationCodeForm code={fixture} pending={false} onCancel={() => {}} onSave={save} />)
    await user.click(screen.getByRole("checkbox", { name: "Create bots" }))
    await user.click(screen.getByRole("checkbox", { name: "Create servers" }))
    await user.click(screen.getByRole("button", { name: "Save changes" }))
    expect(save).toHaveBeenCalledWith(expect.objectContaining({ permissions: [{ permission: "server.create", limit: 64, period: "hour" }] }), false)
    expect(await screen.findByRole("alert")).toHaveTextContent("Try again later")
    expect(screen.getByRole("textbox", { name: "Name" })).toHaveValue("Build script")
  })
  it("uses native integer boundaries and disables controls during submit", async () => {
    const view = render(<AutomationCodeForm code={fixture} pending={false} onCancel={() => {}} onSave={vi.fn()} />)
    await setupUser().click(screen.getByRole("button", { name: "Advanced" }))
    view.rerender(<AutomationCodeForm code={fixture} pending onCancel={() => {}} onSave={vi.fn()} />)
    expect(screen.getByRole("spinbutton")).toHaveAttribute("max", "1536")
    expect(screen.getByRole("spinbutton")).toHaveAttribute("min", "1")
    expect(screen.getByRole("spinbutton")).toHaveAttribute("step", "1")
    expect(screen.getByRole("spinbutton")).toBeDisabled()
    expect(screen.getByRole("button", { name: "Saving…" })).toBeDisabled()
  })
})

describe("Automation settings", () => {
  it("shows loading and errors without a false empty state", async () => {
    state.isPending = true
    const view = render(<AutomationSettings userId="owner" />)
    expect(screen.getByRole("status", { name: "Loading access codes" })).toBeInTheDocument()
    state.isPending = false; state.isError = true
    view.rerender(<AutomationSettings userId="owner" />)
    expect(screen.getByRole("alert")).toHaveTextContent("Could not load access codes")
    expect(screen.queryByText(/No access codes yet/)).not.toBeInTheDocument()
    await setupUser().click(screen.getByRole("button", { name: "Try again" }))
    expect(state.refetch).toHaveBeenCalledOnce()
  })
  it("shows the secret only after creation and clears it with Done", async () => {
    const user = setupUser()
    state.execute.mockImplementation(async (_command, created) => created?.({ accessCode: fixture, secret: "synthetic-secret-for-test" }))
    render(<AutomationSettings userId="owner" />)
    await user.click(screen.getByRole("button", { name: "Create access code" }))
    await user.type(screen.getByRole("textbox", { name: "Name" }), "Test")
    await user.click(screen.getByRole("checkbox", { name: "Create bots" }))
    await user.click(screen.getByRole("button", { name: "Create access code" }))
    expect(await screen.findByDisplayValue("synthetic-secret-for-test")).toBeInTheDocument()
    await user.click(screen.getByRole("button", { name: "Done" }))
    expect(screen.getByRole("heading", { name: "Have you saved your access code?" })).toBeInTheDocument()
    await user.click(screen.getByRole("button", { name: "Cancel" }))
    expect(screen.getByDisplayValue("synthetic-secret-for-test")).toBeInTheDocument()
    await user.click(screen.getByRole("button", { name: "Done" }))
    await user.click(screen.getByRole("button", { name: "I've saved it" }))
    expect(screen.queryByDisplayValue("synthetic-secret-for-test")).not.toBeInTheDocument()
  })
  it("keeps the one-time code selectable when clipboard access fails", async () => {
    const user = setupUser()
    const copy = vi.spyOn(navigator.clipboard, "writeText").mockRejectedValue(new Error("Clipboard denied"))
    state.execute.mockImplementation(async (_command, created) => created?.({ accessCode: fixture, secret: "synthetic-only-copy-test" }))
    render(<AutomationSettings userId="owner" />)
    await user.click(screen.getByRole("button", { name: "Create access code" }))
    await user.type(screen.getByRole("textbox", { name: "Name" }), "Test")
    await user.click(screen.getByRole("button", { name: "Create access code" }))
    await user.click(await screen.findByRole("button", { name: "Copy code" }))
    expect(screen.getByRole("status")).toHaveTextContent("Copy failed. Select the code and copy it manually.")
    expect(screen.getByDisplayValue("synthetic-only-copy-test")).toHaveAttribute("readonly")
    copy.mockRestore()
  })
  it("shows a compact permission summary and preserves expiration when editing details", async () => {
    state.data = { accessCodes: [fixture] }; state.execute.mockResolvedValue(undefined)
    const user = setupUser()
    render(<AutomationSettings userId="owner" />)
    expect(screen.getByText("Create bots")).toBeInTheDocument()
    expect(screen.queryByText(/12\/day/)).not.toBeInTheDocument()
    await user.click(screen.getByRole("button", { name: "Edit Build script" }))
    await user.click(screen.getByRole("button", { name: "Advanced" }))
    expect(screen.getByRole("spinbutton")).toHaveValue(12)
    await user.click(screen.getByRole("button", { name: "Save changes" }))
    expect(state.execute).toHaveBeenCalledWith({ kind: "update", id: fixture.id, data: { name: fixture.name, permissions: fixture.permissions } })
  })
  it("confirms the named code before deletion and retains it on failure", async () => {
    state.data = { accessCodes: [fixture] }; state.execute.mockRejectedValue(new Error("Deletion unavailable"))
    const user = setupUser()
    render(<AutomationSettings userId="owner" />)
    await user.click(screen.getByRole("button", { name: "Delete Build script" }))
    expect(screen.getByRole("heading", { name: "Delete “Build script”?" })).toBeInTheDocument()
    await user.click(screen.getByRole("button", { name: "Cancel" }))
    expect(state.execute).not.toHaveBeenCalled()
    await user.click(screen.getByRole("button", { name: "Delete Build script" }))
    await user.click(screen.getByRole("button", { name: "Delete code" }))
    await waitFor(() => expect(state.execute).toHaveBeenCalledWith({ kind: "delete", id: fixture.id }))
    expect(await screen.findByRole("alert")).toHaveTextContent("Deletion unavailable")
    expect(screen.getByText("Build script")).toBeInTheDocument()
  })
})
